import os
import shutil
import subprocess
import tkinter as tk
from pathlib import Path
from tkinter import messagebox
from tkinter import ttk

import psycopg
from psycopg import sql
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent
ENV_FILE = BASE_DIR / ".env"

def find_postgres():
    psql = shutil.which("psql")
    services = []
    try:
        out = subprocess.check_output(
            ["powershell", "-NoProfile", "-Command",
             "Get-Service -Name 'postgres*' -ErrorAction SilentlyContinue | "
             "Select-Object -ExpandProperty Name"],
            text=True, timeout=5
        )
        services = [x.strip() for x in out.splitlines() if x.strip()]
    except Exception:
        pass
    return psql, services

def write_env(host, port, dbname, user, password):
    text = (
        f"DB_HOST={host}\nDB_PORT={port}\nDB_NAME={dbname}\n"
        f"DB_USER={user}\nDB_PASSWORD={password}\n"
        "N8N_ATTENDANCE_WEBHOOK_URL=http://localhost:5678/webhook/attendance\n"
        "N8N_CREATE_STUDENT_WEBHOOK_URL=http://localhost:5678/webhook/create-student\n"
    )
    ENV_FILE.write_text(text, encoding="utf-8")

def create_schema(host, port, dbname, user, password):
    with psycopg.connect(
        host=host, port=port, dbname=dbname, user=user, password=password
    ) as conn:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS students (
                    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    phone_number TEXT,
                    email TEXT,
                    address TEXT
                )
            """)
            cur.execute("""
                CREATE SEQUENCE IF NOT EXISTS attendance_id_seq
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS attendance (
                    id BIGINT NOT NULL DEFAULT nextval('attendance_id_seq'),
                    student_id BIGINT NOT NULL REFERENCES students(student_id),
                    date DATE NOT NULL,
                    time TIME NOT NULL,
                    status TEXT NOT NULL,
                    PRIMARY KEY (id)
                )
            """)
            cur.execute("ALTER SEQUENCE attendance_id_seq OWNED BY attendance.id")
        conn.commit()

def database_exists(host, port, maintenance_db, user, password, dbname):
    with psycopg.connect(
        host=host, port=port, dbname=maintenance_db,
        user=user, password=password
    ) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (dbname,))
            return cur.fetchone() is not None

def create_database(host, port, maintenance_db, user, password, dbname):
    with psycopg.connect(
        host=host, port=port, dbname=maintenance_db,
        user=user, password=password, autocommit=True
    ) as conn:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(dbname)))
def setup_database(host, port, dbname, user, password):
    if not database_exists(host, port, "postgres", user, password, dbname):
        create_database(host, port, "postgres", user, password, dbname)
    create_schema(host, port, dbname, user, password)
    write_env(host, port, dbname, user, password)

class DatabaseSetup:
    def __init__(self, parent=None):
        self.result = False
        self.root = tk.Toplevel(parent) if parent else tk.Tk()
        self.root.title("Smart Attendance - Database Setup")
        self.root.geometry("560x500")
        self.root.resizable(False, False)
        self.root.configure(bg="#0b1220")
        self.build()
        self.root.protocol("WM_DELETE_WINDOW", self.cancel)
        self.root.grab_set() if parent else None

    def field(self, label, value, show=None):
        row = tk.Frame(self.root, bg="#0b1220")
        row.pack(fill="x", padx=35, pady=7)
        tk.Label(row, text=label, width=15, anchor="w",
                 fg="#f5f7fb", bg="#0b1220",
                 font=("Segoe UI", 10)).pack(side="left")
        entry = tk.Entry(row, width=35, show=show,
                         bg="#16243b", fg="#f5f7fb",
                         insertbackground="#f5f7fb",
                         relief="flat")
        entry.insert(0, value)
        entry.pack(side="left", ipady=6)
        return entry

    def build(self):
        tk.Label(self.root, text="First-Time Database Setup",
                 font=("Segoe UI", 21, "bold"),
                 fg="#f5f7fb", bg="#0b1220").pack(pady=(28, 5))
        tk.Label(self.root, text="Local PostgreSQL detected. Configure the attendance database.",
                 font=("Segoe UI", 10), fg="#8fa1b8", bg="#0b1220").pack(pady=(0, 18))
        psql, services = find_postgres()
        detected = "Service detected" if services else ("psql detected" if psql else "PostgreSQL not detected")
        self.detect_label = tk.Label(self.root, text=detected,
                                     fg="#27c78a" if services or psql else "#ff6b6b",
                                     bg="#0b1220", font=("Segoe UI", 10, "bold"))
        self.detect_label.pack(pady=(0, 5))
        self.host = self.field("Host", "localhost")
        self.port = self.field("Port", "5432")
        self.db = self.field("Database", "attendance_db")
        self.user = self.field("Username", "postgres")
        self.password = self.field("Password", "", show="*")
        self.status = tk.Label(self.root, text="Enter the PostgreSQL password, then click Setup.",
                               fg="#8fa1b8", bg="#0b1220", font=("Segoe UI", 9))
        self.status.pack(pady=10)
        tk.Button(self.root, text="Setup Database", command=self.run_setup,
                  bg="#4f8cff", fg="white", relief="flat",
                  font=("Segoe UI", 11, "bold"), padx=25, pady=9).pack(pady=8)
        tk.Button(self.root, text="Cancel", command=self.cancel,
                  bg="#16243b", fg="#f5f7fb", relief="flat",
                  font=("Segoe UI", 9), padx=20, pady=7).pack()

    def run_setup(self):
        values = [self.host.get().strip(), self.port.get().strip(),
                  self.db.get().strip(), self.user.get().strip(), self.password.get()]
        if not all(values):
            messagebox.showerror("Missing information", "Please fill in all database fields.", parent=self.root)
            return
        self.status.config(text="Connecting and preparing database...")
        self.root.update_idletasks()
        try:
            setup_database(*values)
            self.result = True
            messagebox.showinfo("Setup complete",
                                "PostgreSQL is configured and the attendance tables are ready.",
                                parent=self.root)
            self.root.destroy()
        except Exception as exc:
            self.status.config(text="Setup failed. Check the settings and PostgreSQL service.")
            messagebox.showerror("Database setup failed",
                                 f"{type(exc).__name__}: {exc}",
                                 parent=self.root)

    def cancel(self):
        self.result = False
        self.root.destroy()

def needs_setup():
    if not ENV_FILE.exists():
        return True
    load_dotenv(ENV_FILE, override=True)
    required = ["DB_HOST", "DB_PORT", "DB_NAME", "DB_USER", "DB_PASSWORD"]
    if any(not os.getenv(k) for k in required):
        return True
    try:
        with psycopg.connect(
            host=os.getenv("DB_HOST"), port=os.getenv("DB_PORT"),
            dbname=os.getenv("DB_NAME"), user=os.getenv("DB_USER"),
            password=os.getenv("DB_PASSWORD"), connect_timeout=3
        ) as conn:
            with conn.cursor() as cur:
                cur.execute("SELECT to_regclass('public.students'), to_regclass('public.attendance')")
                row = cur.fetchone()
                return not row or row[0] is None or row[1] is None
    except Exception:
        return True

def ensure_database_setup():
    if not needs_setup():
        return True
    app = tk.Tk()
    app.withdraw()
    wizard = DatabaseSetup(app)
    app.wait_window(wizard.root)
    app.destroy()
    return wizard.result
